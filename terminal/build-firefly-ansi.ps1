# Firefly logo for the fastfetch header. Pixel art traced from
# assets\firefly.png and rendered in Unicode half-blocks.
#
# Legend:
#   #  = full block  █
#   U  = upper half  ▀
#   L  = lower half  ▄
#   .  = empty

$design = @"
..........................L......L..........................
..........................U#....#U..........................
L############################..############################L
U############################..############################U
..#######################UU##..##UU#######################..
...U#############UUUU...LL###..###LL...UUUU#############U...
.....U###UUUU......LLL#####U....U#####LLL......UUUU###U.....
...............LLL#######U........U#######LLL...............
...........LLL##########............##########LLL...........
...........############.L#L......L#L.############...........
.............U#######U..###......###..U#######U.............
.................U#U..L#####L..L#####L..U#U.................
....................L##U.####..####.U##L....................
....................U...L####..####L...U....................
........................##U##..##U##........................
.......................#U..##..##..U#.......................
.......................U...##..##...U.......................
...........................##..##...........................
...........................##..##...........................
...........................##..##...........................
...........................##..##...........................
...........................##..##...........................
...........................##..##...........................
...........................##..##...........................
...........................##..##...........................
...........................##..##...........................
"@

$fg = "230;226;205"
$ESC = [char]27
$lines = $design -split "`r?`n" | Where-Object { $_.Trim().Length -gt 0 }

$cols = ($lines | Measure-Object -Property Length -Maximum).Maximum
$rows = $lines.Count

$out = [System.Text.StringBuilder]::new()
for ($y = 0; $y -lt $rows; $y++) {
    $row = $lines[$y].PadRight($cols, '.')
    $painted = [System.Text.StringBuilder]::new()
    for ($x = 0; $x -lt $cols; $x++) {
        $c = $row[$x]
        switch ($c) {
            '#' { [void]$painted.Append("$ESC[38;2;${fg}m" + [char]0x2588) }
            'U' { [void]$painted.Append("$ESC[38;2;${fg}m" + [char]0x2580) }
            'L' { [void]$painted.Append("$ESC[38;2;${fg}m" + [char]0x2584) }
            default { [void]$painted.Append(' ') }
        }
    }
    [void]$out.Append($painted.ToString())
    [void]$out.Append("$ESC[0m")
    [void]$out.AppendLine()
}

$dst = 'D:\Tools\terminal\assets\firefly.txt'
$trimmed = $out.ToString().TrimEnd("`r","`n")
Set-Content -Path $dst -Value $trimmed -Encoding UTF8 -NoNewline
"Wrote: $dst  ($([math]::Round((Get-Item $dst).Length/1KB, 1)) KB, $rows rows)"
